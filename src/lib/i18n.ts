export type VerdictKey = 'true' | 'mostly' | 'misleading' | 'false';
export function verdictKey(v: string): VerdictKey {
  const s = v.trim().toLowerCase();
  if (s === 'true' || s === 'सही') return 'true';
  if (s === 'mostly true' || s === 'ज़्यादातर सही' || s === 'ज्यादातर सही') return 'mostly';
  if (s === 'misleading' || s === 'भ्रामक') return 'misleading';
  if (s === 'false' || s === 'गलत' || s === 'ग़लत') return 'false';
  throw new Error(`Unknown fact-check verdict "${v}"`);
}
export const VERDICT_ORDER: VerdictKey[] = ['true', 'mostly', 'misleading', 'false'];
